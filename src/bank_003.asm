LinkHandshake::
	call WaitSerialTransfer
	ldh a, [rSB]
	ld b, a
	cp $f0
	jr z, jr_003_4071

	cp $f1
	jr z, jr_003_4071

	cp $f2
	jr nz, jr_003_4049

	ld a, [wLinkChoice]
	and $7f
	cp $02
	jr z, jr_003_405e

	jr jr_003_4056

jr_003_4049:

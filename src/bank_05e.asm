;@ def StartSkillAnimSprite_5E(x: a)
;@ path: battle/skillanim
;@ The same as StartSkillAnimSprite_5C, for the sprite sets of bank $5E.
;@ test: skip calls a routine in another bank
StartSkillAnimSprite_5E::
;> wBattleAnimRunning = 1
	ld a, $01
	ld [wBattleAnimRunning], a
;> x = 0
;> if wSkillAnimPhase:
	ld a, [wSkillAnimPhase]
	or a
	jr z, .start

;>     if wItemMsgGroup >= 7:
;>@stop         wSkillAnimSprites = 0; wBattleAnimRunning = 0; return
	ld a, [wItemMsgGroup]
	cp $07
	jr nc, .stop

;>@sx     x = SkillAnimStartX_5E[2 * wItemMsgGroup]
	add a
	ld hl, SkillAnimStartX_5E
	add l
	ld l, a
	ld a, $00
	adc h
;=@sx
	ld h, a
	ld a, [hl]

.start
;> hSpriteX = x
	ld hl, hSpriteX
	ld a, a
	ld [hli], a
	ld a, $00
	ld [hli], a
;> hSpriteY = 0x60
	ld a, $60
	ld [hli], a
	ld a, $00
	ld [hli], a
;> hSpriteSet = wSkillAnimSet; hSpriteFrame = 0
	ld a, [wSkillAnimSet]
	ld [hli], a
	ld a, $00
	ld [hli], a
;> hSpriteTileBase = 0; hSpriteAttr = 0
	ld a, $00
	ld [hli], a
	ld a, $00
	ld [hli], a
;> wSkillAnimSprites = 1
	ld a, $01
	ld [wSkillAnimSprites], a
;> wPlayerAnimPtr = 0xDD63
	ld hl, wBattleAnimSet
	ld a, l
	ld [wPlayerAnimPtr], a
	ld a, h
	ld [wPlayerAnimPtr + 1], a
;> GetAnimationFirstPose()
	ld hl, far_GetAnimationFirstPose
	rst $10
;> wPlayerAnimPtr = 0xDD62
	ld hl, wBattleAnimRunning
	ld a, l
	ld [wPlayerAnimPtr], a
	ld a, h
	ld [wPlayerAnimPtr + 1], a
	ret

.stop
;=@stop
	xor a
	ld [wSkillAnimSprites], a
	xor a
	ld [wBattleAnimRunning], a
	ret



;@ def DrawSkillAnimFrame_5E(sets: de)
;@ path: battle/skillanim
;@ The same as DrawSkillAnimFrame_5C.
;@ test: skip writes OAM entries through pointer tables
DrawSkillAnimFrame_5E::
;> if hOAMCount >= 40:
;>     return
	ldh a, [hOAMCount]
	cp $28
	jr nc, .done

;> entry = sets + 2 * hSpriteSet
	ldh a, [hSpriteSet]
	ld l, a
	ld h, $00
	add hl, hl
	add hl, de
;> frames = mem16[entry]
	ld e, [hl]
	inc hl
	ld d, [hl]
;> entry = frames + 2 * hSpriteFrame
	ldh a, [hSpriteFrame]
	ld l, a
	ld h, $00
	add hl, hl
	add hl, de
;> frame = mem16[entry]
	ld e, [hl]
	inc hl
	ld d, [hl]
;> oam = wShadowOAM + 4 * hOAMCount
	ldh a, [hOAMCount]
	sla a
	sla a
	ld l, a
	ld h, $c0

.entry
;>@loop while True:
;>     y = mem[frame]; frame += 1
	ld a, [de]
	inc de
;>     if y == 0x80:                     # end of the frame
;>         break
	cp $80
	jr z, .done

;>     mem[oam] = (hSpriteY + y + 0x10) & 0xFF
	ld b, a
	ldh a, [hSpriteY]
	add b
	add $10
	ld [hli], a
;>     x = mem[frame]; frame += 1
	ld a, [de]
	inc de
	ld b, a
;>     mem[oam + 1] = (hSpriteX + x + 8) & 0xFF
	ldh a, [hSpriteX]
	add b
	add $08
	ld [hli], a
;>     mem[oam + 2] = (hSpriteTileBase + mem[frame]) & 0xFF; frame += 1
	ldh a, [hSpriteTileBase]
	ld b, a
	ld a, [de]
	inc de
	add b
	ld [hli], a
;>     mem[oam + 3] = hSpriteAttr ^ mem[frame]; frame += 1
	ld a, [de]
	inc de
	ld b, a
	ldh a, [hSpriteAttr]
	xor b
	ld [hli], a
;>     oam += 4; hOAMCount += 1
	ldh a, [hOAMCount]
	inc a
	ldh [hOAMCount], a
;>     if hOAMCount >= 40:
;>         break
	cp $28
;=@loop
	jr c, .entry

.done
	ret



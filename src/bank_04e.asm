;@ def StartText_4E()
;@ path: text/dialogue
;@ Starts printing text wTextGroup / wTextIndex of bank $4E. Some text numbers of this bank are
;@ kept in bank $4F: those are renumbered and handed to that bank.
;@ test: skip runs the text code with this bank switched in
StartText_4E::
;> if wTextGroup == 0x01:
	ld a, [wTextGroup]
	cp $01
	jr nz, jr_04e_40ca

;>     wTextGroup = 0x01
	ld a, $01
	ld [wTextGroup], a
;>     return StartText_4F()                    # that bank holds these texts
	ld hl, far_StartText_4F
	rst $10
	ret


jr_04e_40ca:
;> if wTextIndex >= 0x58:
	ld a, [wTextIndex]
	cp $58
	jr c, jr_04e_40e0

;>     wTextIndex -= 0x58
	sub $58
	ld [wTextIndex], a
;>     wTextGroup = 0x00
	ld a, $00
	ld [wTextGroup], a
;>     return StartText_4F()                    # that bank holds these texts
	ld hl, far_StartText_4F
	rst $10
	ret


jr_04e_40e0:
;> StartText(FarTable_4E + 6)
	ld de, FarTable_4E + 6
	call StartText
	ret


